def _embedder_command(compose) -> list[str]:
    return [str(part) for part in compose["services"]["embedder"]["command"]]


def _option(command: list[str], name: str) -> str:
    return command[command.index(name) + 1]


def test_the_only_model_run_in_the_stack_is_the_embedder_behind_the_embedding_alias(gateway, compose):
    """Text is generated by the providers; the one model served here is the embedding one, and
    only the alias the backend embeds with reaches it."""
    local = {d["model_name"]: d["litellm_params"]["api_base"] for d in _deployments(gateway) if "api_base" in d["litellm_params"]}

    assert local == {Settings.model_fields["embedding_model"].default: "http://embedder:80/v1"}
    assert not {name for name in compose["services"] if "ollama" in name}


