def _mat_khau_vai_tro(ten_vai_tro: str, bien_url: str) -> str:
    """Mật khẩu của vai trò lấy từ chính URL mà ứng dụng sẽ dùng để kết nối.

    Chỉ đọc đúng một biến, không nhận thêm biến <TÊN>_DB_PASSWORD nào khác làm
    nguồn thay thế: hai nguồn thì sẽ có lúc lệch nhau, và hậu quả là vai trò được
    tạo với mật khẩu khác mật khẩu ứng dụng dùng, lỗi chỉ lộ ra lúc chạy."""
    url = os.environ.get(bien_url)
    if not url:
        raise RuntimeError(
            f"Thiếu {bien_url}. Migration cần nó để đặt mật khẩu cho vai trò {ten_vai_tro}."
        )
    mat_khau = make_url(url).password
    if not mat_khau:
        raise RuntimeError(f"{bien_url} không có mật khẩu, không tạo được vai trò {ten_vai_tro}.")
    return mat_khau


